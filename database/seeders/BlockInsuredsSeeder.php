    'T0004376',
    'T0004379',
];

        $statusId = 3;

        $this->command->info('');
        $this->command->info('========================================');
        $this->command->info('INICIO DE ACTUALIZACIÓN MASIVA');
        $this->command->info('========================================');
        $this->command->info('Total de folios recibidos: ' . count($folios));
        $this->command->info('');

        $actualizados = 0;
        $noEncontrados = [];
        $errores = [];

        DB::beginTransaction();

        try {

            foreach ($folios as $folio) {

                try {

                    $insured = SocioeconomicBenefitsInsured::where('file_number', $folio)->first();

                    if (!$insured) {

                        $noEncontrados[] = $folio;

                        $this->command->warn(
                            "[NO ENCONTRADO] {$folio}"
                        );

                        continue;
                    }

                    $estatusAnterior = $insured->affiliation_status_id;

                    $insured->update([
                        'affiliation_status_id' => $statusId,
                    ]);

                    $actualizados++;

                    $this->command->info(
                        "[OK] {$folio} | Estatus {$estatusAnterior} -> {$statusId}"
                    );

                } catch (Throwable $e) {

                    $errores[] = [
                        'folio' => $folio,
                        'error' => $e->getMessage(),
                    ];

                    $this->command->error(
                        "[ERROR] {$folio} | {$e->getMessage()}"
                    );
                }
            }

            DB::commit();
            $executionTime = microtime(true) - $startTime;

            $minutes = floor($executionTime / 60);
            $seconds = round($executionTime % 60, 2);
            $this->command->info('');
            $this->command->info('========================================');
            $this->command->info('PROCESO FINALIZADO');
            $this->command->info('========================================');
            $this->command->info("Actualizados: {$actualizados}");
            $this->command->info("No encontrados: " . count($noEncontrados));
            $this->command->info("Errores: " . count($errores));
            $this->command->info(
                "Tiempo total: {$minutes} min {$seconds} seg"
            );           

            if (!empty($noEncontrados)) {

                $this->command->warn('');
                $this->command->warn('FOLIOS NO ENCONTRADOS');

                foreach ($noEncontrados as $folio) {
                    $this->command->line($folio);
                }
            }

            if (!empty($errores)) {

                $this->command->error('');
                $this->command->error('FOLIOS CON ERROR');

                foreach ($errores as $error) {

                    $this->command->line(
                        $error['folio'] . ' => ' . $error['error']
                    );
                }
            }

        } catch (Throwable $e) {

            DB::rollBack();

            $this->command->error('');
            $this->command->error('========================================');
            $this->command->error('TRANSACCIÓN CANCELADA');
            $this->command->error('========================================');
            $this->command->error($e->getMessage());

            throw $e;
        }
    }
